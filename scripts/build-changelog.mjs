#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const ENTRIES_DIR = join(ROOT, 'changelog', 'entries');
const OUT_FILE = join(ROOT, 'src', 'generated', 'changelog-data.ts');

const VALID_TYPES = ['feature', 'improvement', 'fix', 'breaking', 'announcement'];

function parseFrontmatter(content, file) {
  if (!content.startsWith('---\n')) {
    throw new Error(`${file}: missing frontmatter (must start with '---')`);
  }
  const end = content.indexOf('\n---', 4);
  if (end === -1) throw new Error(`${file}: unterminated frontmatter`);
  const fm = content.slice(4, end);
  const body = content.slice(end + 4).replace(/^\n+/, '').trim();

  const meta = {};
  for (const raw of fm.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    const idx = line.indexOf(':');
    if (idx === -1) throw new Error(`${file}: malformed frontmatter line: ${line}`);
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (value.startsWith('[') && value.endsWith(']')) {
      value = value
        .slice(1, -1)
        .split(',')
        .map((s) => s.trim().replace(/^["']|["']$/g, ''))
        .filter(Boolean);
    } else {
      value = value.replace(/^["']|["']$/g, '');
    }
    meta[key] = value;
  }
  return { meta, body };
}

function buildSlug(file) {
  return file.replace(/\.md$/, '');
}

function main() {
  const files = readdirSync(ENTRIES_DIR).filter((f) => f.endsWith('.md'));
  const entries = files.map((file) => {
    const content = readFileSync(join(ENTRIES_DIR, file), 'utf8');
    const { meta, body } = parseFrontmatter(content, file);

    if (!meta.date) throw new Error(`${file}: missing 'date'`);
    if (!meta.type) throw new Error(`${file}: missing 'type'`);
    if (!meta.title) throw new Error(`${file}: missing 'title'`);
    if (!VALID_TYPES.includes(meta.type)) {
      throw new Error(`${file}: invalid type '${meta.type}' (allowed: ${VALID_TYPES.join(', ')})`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) {
      throw new Error(`${file}: invalid date '${meta.date}' (expected YYYY-MM-DD)`);
    }

    const tags = Array.isArray(meta.tags) ? meta.tags : meta.tags ? [meta.tags] : [];

    return {
      id: buildSlug(file),
      date: meta.date,
      type: meta.type,
      title: meta.title,
      summary: body.split('\n')[0] || '',
      body_md: body,
      tags,
      url: meta.url || null,
    };
  });

  entries.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.id < b.id ? 1 : -1));

  mkdirSync(dirname(OUT_FILE), { recursive: true });
  const out = `// AUTO-GENERATED by scripts/build-changelog.mjs — do not edit.
import type { ChangelogEntry } from '@/types/changelog';

export const CHANGELOG_ENTRIES: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
  writeFileSync(OUT_FILE, out);
  console.log(`Generated ${entries.length} changelog entries → ${OUT_FILE}`);
}

main();
